function[f] = coulomb(dq,S,alpha)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   [f] = coulomg(dq,S,alpha)
%
%   シグモイド関数で近似したクーロン摩擦
%       f = S( 1/(1+exp(-alpha*dq)) -1/2 )
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

num = size(dq,1);
f = nan(num,1);

for i = 1:num
    f(i) = S(i)*( 1/(1+exp(-alpha(i)*dq(i))) -1/2 );
end

end